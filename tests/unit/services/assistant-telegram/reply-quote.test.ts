/**
 * A Telegram reply to an ordinary message reaches the Assistant with what it replied to: the
 * user's words stay the message body, and the replied message rides after them as a
 * `ppm-reply-v1` block (data only) saying who sent it, when, what it carried and its first lines.
 * Old text cannot pass for the user's words: block markers, `<ppm-…>` tags and the user-words
 * header inside it are all defused. Cards are still answered as before; a card with no manager
 * chat is quoted when its reply goes to the Assistant.
 *
 * PPM_TELEGRAM_REPLY_QUOTE_PREVIEW=<file> writes a readable log of what the Assistant received.
 */
