/**
 * Question cards asked one question at a time, against the fake Bot API: the message is edited
 * from step to step, only Send answers the card, and it answers every question at once.
 *
 * With `PPM_TELEGRAM_WIZARD_PREVIEW=<file>` set, every step of the three-question walk is written
 * there as Markdown (the message text and its keyboard), to look at before trying it on a phone.
 */
import { afterAll, describe, expect, it } from "bun:test";
import { writeFileSync } from "node:fs";
import { clientFor, connectChat, freshChat, memoryState, queueFor, useFakeTelegram } from "./bridge-test-kit.ts";
import { chatControl, setChatControl, type ApprovalAnswer, type ChatControl, type LiveApprovalCard } from "../../../../src/services/chat-control/chat-control.ts";
import { AssistantTelegramCards } from "../../../../src/services/assistant-telegram/assistant-telegram-cards.ts";
import { ButtonCodes } from "../../../../src/services/assistant-telegram/assistant-telegram-button-codes.ts";
import type { BridgeAction } from "../../../../src/services/assistant-telegram/assistant-telegram-actions.ts";
import { normalizeClaudeQuestions, normalizeCodexQuestions, type NormalizedQuestion } from "../../../../src/shared/approval-questions.ts";
import type { TelegramCallbackQuery } from "../../../../src/services/telegram/telegram-types.ts";

const fake = useFakeTelegram();
const client = clientFor(fake);

const answered: Array<{ sessionId: string; requestId: string; answer: ApprovalAnswer }> = [];
let cards!: AssistantTelegramCards;
const previous = chatControl();
setChatControl({
  answerApproval(sessionId, requestId, answer) {
    answered.push({ sessionId, requestId, answer });
    cards.resolved({ sessionId, requestId, approved: answer.approved, reason: "answered", by: "telegram", answers: answer.answersById });
    return "answered";
  },
} as Partial<ChatControl> as ChatControl);

const preview: string[] = [];
afterAll(() => {
  setChatControl(previous);
  const out = process.env.PPM_TELEGRAM_WIZARD_PREVIEW;
  if (out && preview.length) writeFileSync(out, `# Telegram question card, step by step\n\nGenerated by \`tests/unit/services/assistant-telegram/question-wizard.test.ts\` against the fake Bot API.\n\n${preview.join("\n")}`);
});

/** Three questions: one choice, several choices, one choice — the shape the walk below goes through. */
const THREE: NormalizedQuestion[] = normalizeCodexQuestions({
  questions: [
    { id: "env", header: "Env", question: "Which environment should the deploy go to?", options: [{ label: "staging", description: "safe to break" }, { label: "production", description: "customers see it" }] },
    { id: "notify", header: "Notify", question: "Who should hear about it?", options: [{ label: "email" }, { label: "Slack #releases" }, { label: "nobody" }] },
    { id: "when", header: "When", question: "When should it run?", options: [{ label: "now" }, { label: "tonight", description: "after 22:00" }] },
  ],
}).map((q) => (q.id === "notify" ? { ...q, multiSelect: true } : q));

function setup(link = "http://localhost:8080/assistant?session=claude/s") {
  const chat = connectChat(freshChat());
  const queue = queueFor(client);
  const codes = new ButtonCodes<BridgeAction>();
  cards = new AssistantTelegramCards({ queue, state: memoryState(), codes, now: Date.now, sessionLink: async () => link, chatLink: async () => link });
  const card = (questions: NormalizedQuestion[]): LiveApprovalCard => ({ requestId: `req-${crypto.randomUUID()}`, tool: "AskUserQuestion", input: {}, isQuestion: true, questions });
  /** Shows a card (the Assistant's own, or `relay` another chat's) and waits for it to be on Telegram. */
  const show = async (questions: NormalizedQuestion[], relay?: { sessionId: string; manager?: boolean }) => {
    const full = card(questions);
    const before = fake.sent(Number(chat)).length;
    if (relay) cards.relayed(chat, { targetSessionId: relay.sessionId, targetProject: "alpha", targetProvider: "codex", targetTitle: "Deploy chat", card: full, ...(relay.manager ? { manager: true } : {}) });
    else cards.shown(chat, { sessionId: "s", card: full, projectName: "__assistant__", providerId: "claude" });
    const message = await fake.waitFor(() => fake.sent(Number(chat))[before]);
    await queue.whenIdle();
    return { id: message.message_id, requestId: full.requestId };
  };
  const message = (id: number) => fake.sent(Number(chat)).find((m) => m.message_id === id)!;
  const buttons = (id: number) => fake.buttons(Number(chat), id).flat();
  const labels = (id: number) => fake.buttons(Number(chat), id).map((row) => row.map((b) => b.text));
  const pressData = (data: string | undefined) => {
    const found = codes.peek(data, chat);
    if (!found.ok || found.action.kind !== "card") return "no such button";
    return cards.press(chat, found.action, found.group, {} as TelegramCallbackQuery);
  };
  /** Presses the button whose text is `text`, ticked or not, and waits for the edit it makes. */
  const press = async (id: number, text: string) => {
    const data = buttons(id).find((b) => b.text === text || b.text === `✓ ${text}`)?.callback_data;
    const toast = pressData(data);
    await queue.whenIdle();
    return toast;
  };
  return { chat, queue, codes, show, message, buttons, labels, press, pressData };
}

describe("a question card asked one question at a time", () => {
  it("walks three questions in one message, goes back, and answers them all only with Send", async () => {
    const t = setup();
    const sentBefore = fake.sent(Number(t.chat)).length;
    const { id, requestId } = await t.show(THREE);
    const answeredBefore = answered.length;
    const snap = (title: string, toast?: string) => {
      const m = t.message(id);
      preview.push(`## ${title}${toast ? `\n\nToast: _${toast}_` : ""}\n\n\`\`\`text\n${m.text}\n\`\`\`\n\nKeyboard:\n\n${(m.reply_markup?.inline_keyboard ?? []).map((row) => `- ${row.map((b) => `[${b.text}]`).join(" ")}`).join("\n") || "- (none)"}\n`);
    };

    // Question 1: one choice. Its buttons, each naming its whole choice, and no Back.
    expect(t.message(id).text).toContain("Question 1/3");
    expect(t.message(id).text).toContain("Which environment should the deploy go to?");
    expect(t.message(id).text).toContain("staging — safe to break");
    expect(t.message(id).text).not.toContain("Who should hear about it?");
    // A localhost link goes in the text, so the keyboard is the question's choices alone.
    expect(t.labels(id)).toEqual([["staging"], ["production"]]);
    snap("1. Question 1/3 (one choice)");
    const stepOneButton = t.buttons(id).find((b) => b.text === "staging")!.callback_data;

    let toast = await t.press(id, "production");
    expect(toast).toBe("Next question.");
    snap("2. Question 2/3 after picking “production”", toast);
    expect(t.message(id).text).toContain("Question 2/3");
    expect(t.message(id).text).toContain("(choose any)");
    expect(t.labels(id)).toEqual([["email"], ["Slack #releases"], ["nobody"], ["« Back", "Next »"]]);

    // A button of question 1, pressed after the message moved on, changes nothing.
    expect(t.pressData(stepOneButton)).toBe("This button is from an earlier step.");
    expect(await t.press(id, "Next »")).toBe("Tick at least one choice first.");
    expect(await t.press(id, "email")).toBe("Ticked.");
    toast = await t.press(id, "Slack #releases");
    expect(toast).toBe("Ticked.");
    snap("3. Question 2/3 with two choices ticked", toast);
    expect(t.labels(id)).toEqual([["✓ email"], ["✓ Slack #releases"], ["nobody"], ["« Back", "Next »"]]);

    // Back to question 1: the earlier pick shows ticked, and picking again keeps question 2's ticks.
    toast = await t.press(id, "« Back");
    expect(toast).toBe("Back.");
    snap("4. Back to question 1/3", toast);
    expect(t.labels(id)).toEqual([["staging"], ["✓ production"]]);
    expect(await t.press(id, "staging")).toBe("Next question.");
    expect(t.labels(id)).toEqual([["✓ email"], ["✓ Slack #releases"], ["nobody"], ["« Back", "Next »"]]);

    toast = await t.press(id, "Next »");
    expect(toast).toBe("Next question.");
    snap("5. Question 3/3 (one choice)", toast);
    expect(t.message(id).text).toContain("Question 3/3");
    expect(t.labels(id)).toEqual([["now"], ["tonight"], ["« Back"]]);

    toast = await t.press(id, "tonight");
    expect(toast).toBe("Check your answers, then Send.");
    snap("6. Summary", toast);
    const summary = t.message(id).text;
    expect(summary).toContain("Your answers");
    expect(summary).toContain("Env — Which environment should the deploy go to?\n→ staging");
    expect(summary).toContain("→ email, Slack #releases");
    expect(summary).toContain("→ tonight");
    expect(t.labels(id)).toEqual([["« Back", "Send"]]);

    // Back from the summary is question 3, as it was answered.
    expect(await t.press(id, "« Back")).toBe("Back.");
    expect(t.labels(id)).toEqual([["now"], ["✓ tonight"], ["« Back"]]);
    expect(await t.press(id, "tonight")).toBe("Check your answers, then Send.");

    // Nothing reached the chat before Send, and everything did with it.
    expect(answered.length).toBe(answeredBefore);
    toast = await t.press(id, "Send");
    expect(toast).toBe("Answer sent.");
    expect(answered.at(-1)).toEqual({
      sessionId: "s", requestId,
      answer: { approved: true, answersById: { env: ["staging"], notify: ["email", "Slack #releases"], when: ["tonight"] } },
    });
    snap("7. After Send", toast);
    const done = t.message(id);
    expect(done.reply_markup).toBeUndefined();
    expect(done.text).toContain("1. Env — Which environment should the deploy go to?");
    expect(done.text).toContain("Answered here");
    // One message for the whole card: every step was an edit of it.
    expect(fake.sent(Number(t.chat)).length).toBe(sentBefore + 1);
    // Every button fits Telegram's 64 bytes (the fake refuses anything longer, too).
    for (const call of fake.calls) {
      const markup = call.body.reply_markup as { inline_keyboard?: Array<Array<{ callback_data?: string }>> } | undefined;
      for (const b of markup?.inline_keyboard?.flat() ?? []) if (b.callback_data) expect(new TextEncoder().encode(b.callback_data).length).toBeLessThanOrEqual(64);
    }
  });

  it("stops and says so when the card is answered in PPM halfway through", async () => {
    const t = setup();
    const { id, requestId } = await t.show(THREE);
    expect(await t.press(id, "production")).toBe("Next question.");
    const ticked = t.buttons(id).find((b) => b.text === "email")!.callback_data;
    const before = answered.length;
    cards.resolved({ sessionId: "s", requestId, approved: true, reason: "answered", by: "ws", answers: { env: "staging", notify: "nobody", when: "now" } });
    await t.queue.whenIdle();
    const m = t.message(id);
    expect(m.reply_markup).toBeUndefined();
    expect(m.text).toContain("Answered in PPM: staging; nobody; now");
    expect(m.text).not.toContain("Question 2/3");
    // Its buttons were spent with it: a press on one is no longer valid.
    expect(t.codes.peek(ticked, t.chat).ok).toBe(false);
    expect(answered.length).toBe(before);
  });

  it("says a card that ended without an answer is no longer waiting", async () => {
    const t = setup();
    const { id, requestId } = await t.show(THREE);
    await t.press(id, "staging");
    cards.resolved({ sessionId: "s", requestId, approved: false, reason: "request_ended" });
    await t.queue.whenIdle();
    expect(t.message(id).text).toContain("No longer waiting: the request ended without an answer.");
    expect(t.message(id).reply_markup).toBeUndefined();
  });

  it("leaves a card with a typed or private question to PPM: every question shown, no buttons", async () => {
    const t = setup();
    const questions = normalizeCodexQuestions({ questions: [
      { id: "env", question: "Which environment?", options: [{ label: "staging" }, { label: "production" }] },
      { id: "token", question: "API token?", isSecret: true },
    ] });
    const { id } = await t.show(questions);
    const m = t.message(id);
    expect(m.text).toContain("Which environment?");
    expect(m.text).toContain("API token?");
    expect(m.text).toContain("give it in PPM");
    expect(m.text).not.toContain("Question 1/2");
    expect(t.buttons(id)).toEqual([]);
  });

  it("still answers a card with one question and one choice at the first press", async () => {
    const t = setup();
    const questions = normalizeClaudeQuestions({ questions: [{ question: "Màu nào?", header: "Màu", options: [{ label: "Đỏ" }, { label: "Xanh" }], multiSelect: false }] });
    const { id, requestId } = await t.show(questions);
    expect(t.message(id).text).not.toContain("Question 1/1");
    expect(t.labels(id)).toEqual([["Đỏ"], ["Xanh"]]);
    expect(await t.press(id, "Xanh")).toBe("Answer sent.");
    expect(answered.at(-1)).toEqual({ sessionId: "s", requestId, answer: { approved: true, answersById: { [questions[0]!.id]: ["Xanh"] } } });
  });

  it("asks one question that takes several choices with ticks, Next and the summary", async () => {
    const t = setup();
    const questions: NormalizedQuestion[] = [{ id: "q1", question: "Which?", options: [{ label: "a" }, { label: "b" }, { label: "c" }], multiSelect: true, allowsFreeText: true }];
    const { id, requestId } = await t.show(questions);
    expect(t.message(id).text).toContain("Question 1/1");
    expect(t.labels(id)).toEqual([["a"], ["b"], ["c"], ["Next »"]]);
    await t.press(id, "c");
    await t.press(id, "a");
    // Kept in the order the choices are listed.
    expect(await t.press(id, "Next »")).toBe("Check your answers, then Send.");
    expect(t.message(id).text).toContain("→ a, c");
    expect(await t.press(id, "Send")).toBe("Answer sent.");
    expect(answered.at(-1)).toEqual({ sessionId: "s", requestId, answer: { approved: true, answersById: { q1: ["a", "c"] } } });
  });

  it("works the same on another chat's card, and answers that chat", async () => {
    const t = setup();
    const { id, requestId } = await t.show(THREE, { sessionId: "codex-thread-1", manager: true });
    expect(t.message(id).text).toContain("Manager chat “Deploy chat” in alpha is stopped, waiting for your answer");
    expect(t.message(id).text).toContain("Question 1/3");
    await t.press(id, "staging");
    await t.press(id, "nobody");
    await t.press(id, "Next »");
    await t.press(id, "now");
    expect(await t.press(id, "Send")).toBe("Answer sent.");
    expect(answered.at(-1)).toEqual({
      sessionId: "codex-thread-1", requestId,
      answer: { approved: true, answersById: { env: ["staging"], notify: ["nobody"], when: ["now"] } },
    });
  });

  it("keeps the Open in PPM button on every step, and moves the link into the text if Telegram refuses it", async () => {
    const link = "https://ppm.tail1234.ts.net/assistant?session=claude/s";
    const t = setup(link);
    const { id } = await t.show(THREE);
    expect(t.buttons(id).at(-1)?.url).toBe(link);
    fake.failNext("editMessageText", { code: 400, description: "Bad Request: BUTTON_URL_INVALID" });
    expect(await t.press(id, "staging")).toBe("Next question.");
    const m = t.message(id);
    expect(m.text).toContain("Question 2/3");
    expect(m.text).toContain(`Open in PPM: ${link}`);
    expect(t.buttons(id).some((b) => b.url)).toBe(false);
    await t.press(id, "email");
    expect(t.message(id).text).toContain(`Open in PPM: ${link}`);
  });

  it("brings a message that fell behind back to the card's step when a leftover button is pressed", async () => {
    const t = setup();
    const { id } = await t.show(THREE);
    const stepOne = { html: t.message(id).text, markup: t.message(id).reply_markup! };
    expect(await t.press(id, "staging")).toBe("Next question.");
    // The message falls behind the card, as when a press lands before Telegram confirmed the send.
    await client.editMessageText(t.chat, id, stepOne.html, { replyMarkup: stepOne.markup, final: true });
    expect(t.message(id).text).toContain("Question 1/3");
    // Its buttons are now from an earlier step: pressing one changes nothing but redraws.
    expect(t.pressData(stepOne.markup.inline_keyboard[0]![0]!.callback_data)).toBe("This button is from an earlier step.");
    await t.queue.whenIdle();
    expect(t.message(id).text).toContain("Question 2/3");
    expect(t.labels(id)).toEqual([["email"], ["Slack #releases"], ["nobody"], ["« Back", "Next »"]]);
  });

  it("ends the card on Telegram, still waiting in PPM, when a step cannot be drawn", async () => {
    const t = setup();
    const { id } = await t.show(THREE);
    const before = answered.length;
    fake.failNext("editMessageText", { code: 400, description: "Bad Request: message can't be edited" });
    await t.press(id, "staging");
    const m = t.message(id);
    expect(m.text).toContain("could not be updated here — answer it in PPM");
    expect(m.reply_markup).toBeUndefined();
    expect(answered.length).toBe(before);
  });

  it("does not answer with a Send pressed after going back from the summary", async () => {
    const t = setup();
    const { id } = await t.show(THREE);
    await t.press(id, "staging");
    await t.press(id, "email");
    await t.press(id, "Next »");
    await t.press(id, "now");
    const send = t.buttons(id).find((b) => b.text === "Send")!.callback_data;
    await t.press(id, "« Back");
    const before = answered.length;
    expect(t.pressData(send)).toBe("This button is from an earlier step.");
    await t.queue.whenIdle();
    expect(answered.length).toBe(before);
    expect(t.message(id).text).toContain("Question 3/3");
  });

  it("evicts a whole card from a full code store, never part of one", async () => {
    const t = setup();
    const { id } = await t.show(THREE);
    // Newer cards fill the store before anyone presses this one.
    for (let i = 0; i < 495; i++) t.codes.mint(t.chat, `other-${Math.floor(i / 5)}`, { kind: "switch", sessionId: `x${i}` });
    const live = t.buttons(id).map((b) => t.codes.peek(b.callback_data, t.chat).ok);
    expect(new Set(live).size).toBe(1);
  });

  it("keeps the buttons of a card being answered when the code store fills up", async () => {
    const t = setup();
    const { id } = await t.show(THREE);
    // Made after the card, so without a press the card's codes would be the oldest.
    for (let i = 0; i < 400; i++) t.codes.mint(t.chat, "older", { kind: "switch", sessionId: `x${i}` });
    await t.press(id, "staging");
    // The store is full and evicts oldest first: the card in use is not the oldest any more.
    for (let i = 0; i < 120; i++) t.codes.mint(t.chat, "newer", { kind: "switch", sessionId: `y${i}` });
    expect(await t.press(id, "email")).toBe("Ticked.");
    expect(await t.press(id, "« Back")).toBe("Back.");
    expect(await t.press(id, "production")).toBe("Next question.");
  });

  it("hides a secret in a choice on every step and in the summary", async () => {
    const t = setup();
    const secret = "ghp_abcdefghijklmnopqrstuvwxyz0123456789";
    const questions = normalizeCodexQuestions({ questions: [
      { id: "token", question: `Use ${secret}?`, options: [{ label: "yes" }, { label: "no" }] },
      { id: "x", question: "And <b>this</b> & that?", options: [{ label: "<ok>" }, { label: "no" }] },
    ] });
    const { id } = await t.show(questions);
    expect(t.message(id).text).not.toContain(secret);
    await t.press(id, "yes");
    expect(t.message(id).text).toContain("And <b>this</b> & that?");
    await t.press(id, "<ok>");
    expect(t.message(id).text).not.toContain(secret);
    expect(t.message(id).text).toContain("→ <ok>");
  });
});
