import { describe, expect, test } from "bun:test";
import {
  CONTINUE_NUDGE, isRealPrompt, isRealPromptMessage, isRealPromptRecord, promptFirstLine, promptTextOf,
} from "../../../src/shared/user-prompt-kind.ts";
import { withSharedContext } from "../../../src/shared/provider-context.ts";

/** A Claude user record, shaped like the CLI writes it. */
function userRecord(content: unknown, extra: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    parentUuid: null, isSidechain: false, promptId: "11111111-2222-3333-4444-555555555555", type: "user",
    message: { role: "user", content }, uuid: "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", timestamp: "2026-11-01T00:00:00.000Z",
    ...extra,
  };
}

describe("isRealPromptRecord — Claude transcript records", () => {
  test("a typed prompt, as text or as text blocks beside an image, is a prompt", () => {
    expect(isRealPromptRecord(userRecord("add a flag", { promptSource: "sdk" }))).toBe(true);
    expect(isRealPromptRecord(userRecord([{ type: "image", source: {} }, { type: "text", text: "what is this" }]))).toBe(true);
  });

  test("a typed slash command is a prompt, its printed output is not", () => {
    expect(isRealPromptRecord(userRecord("<command-name>/login</command-name>\n<command-message>login</command-message>"))).toBe(true);
    expect(isRealPromptRecord(userRecord("<local-command-stdout>Login successful</local-command-stdout>"))).toBe(false);
    expect(isRealPromptRecord(userRecord("<local-command-caveat>Caveat: generated by a command</local-command-caveat>"))).toBe(false);
  });

  test("tool results and interrupt markers are not prompts", () => {
    expect(isRealPromptRecord(userRecord([{ type: "tool_result", tool_use_id: "toolu_1", content: "ok" }]))).toBe(false);
    expect(isRealPromptRecord(userRecord([{ type: "text", text: "[Request interrupted by user for tool use]" }]))).toBe(false);
    expect(isRealPromptRecord(userRecord("[Request interrupted by user]"))).toBe(false);
  });

  test("task notifications are not prompts, however they are marked", () => {
    const body = "<task-notification><task-id>b1</task-id><status>completed</status></task-notification>";
    expect(isRealPromptRecord(userRecord(body, { origin: { kind: "task-notification" } }))).toBe(false);
    expect(isRealPromptRecord(userRecord("Background agent finished", { turnOrigin: "task_notification" }))).toBe(false);
    expect(isRealPromptRecord(userRecord(body))).toBe(false);
    expect(isRealPromptRecord(userRecord(body, { queueTranscriptOnly: true }))).toBe(false);
  });

  test("meta records — the CLI's continue, image companions, scheduled and peer turns — are not prompts", () => {
    expect(isRealPromptRecord(userRecord([{ type: "text", text: CONTINUE_NUDGE }], { isMeta: true }))).toBe(false);
    expect(isRealPromptRecord(userRecord([{ type: "text", text: "[Image: source: /tmp/a.png]" }], { isMeta: true, turnCompanion: true }))).toBe(false);
    expect(isRealPromptRecord(userRecord("wake up", { isMeta: true, turnOrigin: "scheduled" }))).toBe(false);
  });

  test("PPM's own retry nudge is not a prompt even when written as an ordinary one", () => {
    expect(isRealPromptRecord(userRecord(CONTINUE_NUDGE, { promptSource: "sdk" }))).toBe(false);
  });

  test("a compaction summary and a sidechain record are not prompts", () => {
    const summary = "This session is being continued from a previous conversation that ran out of context.";
    expect(isRealPromptRecord(userRecord(summary, { isCompactSummary: true, isVisibleInTranscriptOnly: true }))).toBe(false);
    expect(isRealPromptRecord(userRecord("subagent task", { isSidechain: true }))).toBe(false);
  });

  test("teammate messages and assistant records are not prompts", () => {
    expect(isRealPromptRecord(userRecord('<teammate-message teammate_id="a">done</teammate-message>'))).toBe(false);
    expect(isRealPromptRecord({ ...userRecord("hello"), type: "assistant" })).toBe(false);
  });

  test("shared context PPM prepends does not make an empty message a prompt", () => {
    expect(isRealPromptRecord(userRecord(withSharedContext("", "project rules")))).toBe(false);
    expect(isRealPromptRecord(userRecord(withSharedContext("fix it", "project rules")))).toBe(true);
  });
});

describe("isRealPromptMessage — messages the chat holds", () => {
  const msg = (content: string, extra: Record<string, unknown> = {}) => ({ role: "user", content, ...extra });

  test("a Codex message a compaction wrote back is never a prompt", () => {
    expect(isRealPromptMessage(msg("the original question", { synthetic: true }))).toBe(false);
    expect(isRealPromptMessage(msg("the original question"))).toBe(true);
  });

  test("a steered Codex message is a prompt by itself; which turn it joins is not decided here", () => {
    expect(isRealPromptMessage(msg("also check the tests"))).toBe(true);
  });

  test("a compact summary message and assistant messages are not prompts", () => {
    expect(isRealPromptMessage(msg("summary", { compaction: { trigger: "auto", preTokens: 1, postTokens: 1, savedTokens: 0 } }))).toBe(false);
    expect(isRealPromptMessage({ role: "assistant", content: "done" })).toBe(false);
  });

  test("isRealPrompt tells the two shapes apart", () => {
    expect(isRealPrompt(msg("hi"))).toBe(true);
    expect(isRealPrompt(userRecord("hi"))).toBe(true);
    expect(isRealPrompt(userRecord("hi", { isMeta: true }))).toBe(false);
  });
});

describe("promptTextOf / promptFirstLine", () => {
  test("a command reads as typed and attachments alone are counted", () => {
    expect(promptTextOf("<command-name>/review</command-name><command-args>src/a.ts</command-args>")).toBe("/review src/a.ts");
    expect(promptTextOf("[Attached files:\n/p/a.png\n/p/b.png\n]")).toBe("2 attached files");
  });

  test("the label is the first line, cut at the limit", () => {
    expect(promptFirstLine("first line\nsecond")).toBe("first line");
    const long = promptFirstLine("x".repeat(300));
    expect(long.length).toBe(200);
    expect(long.endsWith("…")).toBe(true);
  });
});
