/**
 * Vendor the icons the Git Graph webview draws into one module.
 *
 * The panel is a sandboxed iframe, so it cannot use `@/lib/icons` — it gets
 * the same glyphs as SVG strings instead: Fluent System Icons at **20px
 * Regular**, the set the app's own chrome is drawn in (`gen-product-icons.ts`),
 * so a button in the graph and the same button in Source Control look alike.
 * The two glyphs the app keeps from lucide (`GitCommitHorizontal`, `FileDiff`)
 * are kept here too, for the same reason it keeps them: Fluent has neither.
 *
 * Keys are the names the webview script asks for (`ic('push')`); the values
 * are whole `<svg class="ic">` elements, sized by the panel's CSS.
 *
 *   bun scripts/gen-git-graph-icons.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT = resolve(import.meta.dir, "../packages/ext-git-graph/src/webview-icons.generated.ts");

